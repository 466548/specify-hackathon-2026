/**
 * Specify のデモ用 PRD カタログ。
 *
 * 自由入力フォームは廃止し、ここに定義された KintaiKit の 3 新機能 PRD から
 * ユーザーがカード選択するスタイル。Decision Agent が変な入力で誤動作する
 * リスクを 0 にすると同時に、Past PRD（KintaiKit のコア方針）との audit 合流
 * シナリオが毎回確実に再現するよう、3 PRD すべてに「監査記録への言及なし」
 * を意図的に作り込んである。
 *
 * 機能候補の選定理由:
 *   - a (user-add)     : admin 操作系 / 個人情報書き込み → audit 記録の漏れ
 *   - b (shift-auto)   : 自動処理系 / アルゴリズム判断 → 判断根拠ログの漏れ
 *   - c (report-monthly): 配信系 / レポート生成 → 配信履歴ログの漏れ
 *
 * 3 タイプを散らすことで Decision / EdgeCase / PastPRD Agent それぞれが
 * 異なる切り口で論点を出せる構成。
 */

export interface DemoPrd {
  /** 内部 ID。URL や key 用途のスラグ。 */
  id: string;
  /** カードに表示するタイトル。 */
  title: string;
  /** カテゴリラベル（カードのバッジ）。 */
  category: string;
  /** カードに表示する 1-2 行サマリ。 */
  description: string;
  /** バックエンドに送る PRD 本文（Markdown）。 */
  prdText: string;
}

// -----------------------------------------------------------------------------
// PRD a: ユーザー追加モーダル機能（demo-data/sample-prd.md と同一内容）
// -----------------------------------------------------------------------------
const PRD_USER_ADD = `# KintaiKit / ユーザー追加モーダル機能 PRD

## 背景

中小企業向け勤怠管理 SaaS「KintaiKit」では、管理者が従業員を 1 名ずつ追加するフローが必要。現在は CSV 一括インポートのみで、入社者 1 名の追加が煩雑との声が多い。

## 機能概要

管理者画面の「メンバー」一覧画面右上に「+ 追加」ボタンを設置する。クリックするとモーダルが開き、以下のフィールドを入力できる:

- 氏名（必須）
- メールアドレス（必須）
- 部署（プルダウン、必須）
- 雇用形態（正社員 / 契約社員 / アルバイト、必須）
- 入社日（必須）

「保存」ボタンを押すとサーバーにユーザーを作成し、招待メールを送信する。

## 完了条件

- モーダルから 1 ユーザーを作成できる
- 作成後、メンバー一覧に即座に反映される
- 招待メールが送信される
`;

