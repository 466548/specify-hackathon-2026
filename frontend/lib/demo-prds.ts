const PRD_REPORT_MONTHLY = `# KintaiKit / 月次レポート自動配信機能 PRD

## 背景

「KintaiKit」では月初に管理者が手動で前月の勤怠サマリを Excel に貼り付けて経営層に共有している。「数値が出るたびに毎月同じ作業をするのが無駄」との声があり、自動配信化したい。

## 機能概要

毎月 1 日 09:00 (JST) に、各企業の前月分の勤怠サマリを自動生成し、設定された配信先（メールアドレス、最大 5 件）に送信する。

レポート内容:

- 総勤務時間（全従業員合計）
- 残業時間（全従業員合計）
- 欠勤・遅刻件数
- 部署別の勤務時間ランキング Top 3

管理者画面に「月次レポート設定」ページを新設し、配信先メールアドレス・配信タイミング（毎月 1 日 / 月末 等）を変更できるようにする。

## 完了条件

- 設定された日時にレポートが自動配信される
- レポート PDF が添付されている
- 配信先メールアドレスを管理画面から編集できる
`;

