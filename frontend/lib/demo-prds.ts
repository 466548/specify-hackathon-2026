const PRD_SHIFT_AUTO = `# KintaiKit / シフト自動割当機能 PRD

## 背景

「KintaiKit」では現在、管理者がカレンダー画面上で従業員のシフトを手作業で割り当てている。店舗運営型の顧客から「希望休と必要人数の制約を満たす割当を自動でやってほしい」との要望が増えている。

## 機能概要

管理者画面に「シフト自動割当」ボタンを追加する。クリックすると以下の入力を受け取り、来週 1 週間分のシフトを自動生成する:

- 対象週（来週固定、UI 上は週切替も可）
- 必要人数（時間帯ごと、例: 09:00-12:00 = 3 名、12:00-18:00 = 2 名）
- 各従業員の希望休（既存 UI から取得）
- 各従業員の雇用形態別の上限労働時間

割当ロジックはサーバー側で実行し、結果をカレンダーにプレビュー表示する。管理者は「適用」を押せばシフトが確定する。

## 完了条件

- 自動割当の結果がカレンダーに表示される
- 適用後、各従業員のシフトが更新される
- 希望休が反映されている / 必要人数を満たしている
`;

